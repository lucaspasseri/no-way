-- Current desired structure. Initialization is additive, not a migration system.
CREATE TABLE IF NOT EXISTS public.questions (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
  question text NOT NULL CHECK (btrim(question) <> ''),
  answer numeric NOT NULL CHECK (answer NOT IN ('NaN'::numeric, 'Infinity'::numeric, '-Infinity'::numeric)),
  category text,
  source_label text,
  source_url text,
  answer_context text,
  origin text NOT NULL DEFAULT 'manual' CHECK (origin IN ('manual', 'seed', 'ai')),
  status text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'verified', 'rejected')),
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
